export function Evaluation({ run }: { run: Run }) {
  const { summary: s, checks } = run.evaluation!
  const total = checks.length || 1
  return (
    <Panel label="Deterministic checks" aside={<span className="font-mono text-xs text-muted">{checks.length} checks</span>}>
      <div className="flex h-1.5 w-full overflow-hidden bg-raised" role="img"
        aria-label={`${s.pass} passed, ${s.fail} failed, ${s.needs_review} need review`}>
        <div className="bg-ok" style={{ width: `${(s.pass / total) * 100}%` }} />
        <div className="bg-bad" style={{ width: `${(s.fail / total) * 100}%` }} />
        <div className="bg-warn" style={{ width: `${(s.needs_review / total) * 100}%` }} />
      </div>
      <p className="mt-2 mb-4 text-sm">
        <span className="text-ok">{s.pass} passed</span><span className="text-faint"> / </span>
        <span className="text-bad">{s.fail} failed</span><span className="text-faint"> / </span>
        <span className="text-warn">{s.needs_review} need review</span>
      </p>
      <ul>{checks.map((c, i) => <CheckRow key={i} c={c} />)}</ul>
      <p className="mt-4 text-xs text-faint">Rule-based checks on one fictional scenario. Passing them does not show an agent is ready for production.</p>
    </Panel>
  )
}

