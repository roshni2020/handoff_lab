import { useState, type ReactNode } from 'react'
import { api, type Check, type CheckStatus, type Handoff, type Run, type Scenario } from './api'

const time = (iso: string) => { const d = new Date(iso); return d.toLocaleTimeString([], { hour12: false }) + '.' + String(d.getMilliseconds()).padStart(3, '0') }

export function Panel({ label, aside, children, className = '' }: { label: string; aside?: ReactNode; children: ReactNode; className?: string }) {
  return (
    <section className={`rounded-sm border border-line bg-panel ${className}`}>
      <header className="flex items-baseline justify-between gap-3 border-b border-line px-4 py-2.5">
        <h2 className="font-mono text-[11px] uppercase tracking-[0.14em] text-muted">{label}</h2>
        {aside}
      </header>
      <div className="p-4">{children}</div>
    </section>
  )
}

export function Skeleton({ lines = 3 }: { lines?: number }) {
  return (
    <div className="space-y-2.5 animate-pulse" aria-hidden>
      {Array.from({ length: lines }, (_, i) => <div key={i} className="h-3 rounded-sm bg-raised" style={{ width: `${92 - i * 17}%` }} />)}
    </div>
  )
}

