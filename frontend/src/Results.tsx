const TAG: Record<CheckStatus, string> = { pass: 'text-ok border-ok/40', fail: 'text-bad border-bad/50', needs_review: 'text-warn border-warn/50' }
const TAG_TEXT: Record<CheckStatus, string> = { pass: 'Pass', fail: 'Fail', needs_review: 'Review' }
export const Tag = ({ s }: { s: CheckStatus }) =>
  <span className={`inline-block border px-1.5 py-px font-mono text-[10px] uppercase tracking-wider ${TAG[s]}`}>{TAG_TEXT[s]}</span>

export function SourceBanner({ run }: { run: Run }) {
  const [label, cls, text] =
    run.source === 'live_model' ? ['Live', 'border-ok/40 text-ok', `Generated by ${run.model} through the Anthropic API for this fictional scenario. No real customer system was contacted.`]
    : run.source === 'demo_injected_failure' ? ['Injected failure', 'border-bad/50 text-bad', 'A predefined faulty agent response, used to show that the checks catch policy violations. Not from a model call.']
    : ['Demo', 'border-warn/50 text-warn', 'Prewritten sample output. Not a live model response.']
  return (
    <div className={`flex flex-wrap items-baseline gap-x-3 gap-y-1 rounded-sm border bg-panel px-4 py-2.5 ${cls}`}>
      <span className="font-mono text-[11px] uppercase tracking-[0.14em]">{label}</span>
      <span className="text-sm text-fg/90">{text}</span>
    </div>
  )
}

