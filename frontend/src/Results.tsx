export function ReviewPanel({ run, onReviewed }: { run: Run; onReviewed: (r: Run) => void }) {
  const [note, setNote] = useState('')
  const [busy, setBusy] = useState(false)
  const [err, setErr] = useState<string | null>(null)
  const submit = async (status: 'approved' | 'revision_requested') => {
    setBusy(true); setErr(null)
    try { onReviewed(await api.review(run.id, status, note)); setNote('') }
    catch (e) { setErr((e as Error).message) }
    finally { setBusy(false) }
  }
  const status = run.review_status
  return (
    <Panel label="Human review" className="border-accent/40"
      aside={<span className={`font-mono text-xs ${status === 'approved' ? 'text-ok' : status ? 'text-warn' : 'text-muted'}`}>
        {status === 'approved' ? 'Approved' : status ? 'Revision requested' : 'Awaiting review'}
      </span>}>
      {run.reviewed_at && (
        <p className="mb-3 text-sm text-muted">
          {new Date(run.reviewed_at).toLocaleString()}{run.review_note && <>: <span className="text-fg">{run.review_note}</span></>}
        </p>
      )}
      <label htmlFor="note" className="text-xs text-muted">Reviewer note (optional)</label>
      <textarea id="note" value={note} onChange={e => setNote(e.target.value)} rows={2} maxLength={2000}
        className="mt-1 w-full rounded-sm border border-line bg-ink p-2 text-sm placeholder:text-faint focus:border-accent focus:outline-none"
        placeholder="For example: missing the charge date" />
      <div className="mt-3 flex flex-wrap gap-2">
        <button disabled={busy} onClick={() => submit('approved')}
          className="rounded-sm bg-ok px-4 py-2 text-sm font-medium text-ink hover:bg-ok/90 disabled:opacity-50">
          Approve handoff
        </button>
        <button disabled={busy} onClick={() => submit('revision_requested')}
          className="rounded-sm border border-warn/60 px-4 py-2 text-sm font-medium text-warn hover:bg-warn/10 disabled:opacity-50">
          Request revision
        </button>
      </div>
      <p className="mt-3 text-xs text-faint">Simulated workflow. The decision is stored locally and nothing is sent to anyone.</p>
      {err && <p role="alert" className="mt-2 text-sm text-bad">{err}</p>}
    </Panel>
  )
}
